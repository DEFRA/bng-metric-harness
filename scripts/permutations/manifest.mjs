/**
 * Write the machine-readable `manifest.json` and human-readable `index.md`
 * that sit at the root of the permutations output tree, so a tester can see at
 * a glance which fixture demonstrates which scenario.
 */

import { writeFileSync } from "node:fs";
import path from "node:path";

function gainCell(entry) {
  if (!entry.gain) {
    return "—";
  }
  const pct = entry.gain.percentage;
  const shown = pct === null ? "n/a" : `${pct.toFixed(1)}%`;
  return `${entry.gain.expected} (${shown})`;
}

function renderPurposeSection(purpose, entries) {
  const lines = [
    `## ${purpose}`,
    "",
    "| Scenario | Subject | Net gain | Files |",
    "| --- | --- | --- | --- |",
  ];
  for (const entry of entries) {
    const files = `\`${entry.files.baseline}\` · \`${entry.files.postIntervention}\``;
    const subject = `${entry.subject.ref} — ${entry.subject.note}`;
    lines.push(
      `| **${entry.title}**<br>${entry.description} | ${subject} | ${gainCell(entry)} | ${files} |`,
    );
  }
  lines.push("");
  return lines.join("\n");
}

function renderIndex(entries, purposes) {
  const header = [
    "# BNG permutations test data",
    "",
    "Paired baseline / post-intervention GeoPackages covering the scenarios in",
    "BMD-934. Generated by `npm run generate:gpkg:permutations`. Each row lists",
    "the feature a tester should open to exercise the scenario.",
    "",
    `Total scenarios: **${entries.length}** across **${purposes.length}** purposes.`,
    "",
  ].join("\n");
  const sections = purposes.map((purpose) =>
    renderPurposeSection(
      purpose,
      entries.filter((e) => e.purpose === purpose),
    ),
  );
  return `${header}\n${sections.join("\n")}`;
}

/**
 * @param {string} outRoot permutations output root
 * @param {object[]} entries manifest entries, in catalogue order
 * @param {string[]} purposes purpose names, in catalogue order
 */
export function writeManifest(outRoot, entries, purposes) {
  const manifestPath = path.join(outRoot, "manifest.json");
  const indexPath = path.join(outRoot, "index.md");
  writeFileSync(
    manifestPath,
    `${JSON.stringify({ scenarios: entries }, null, 2)}\n`,
  );
  writeFileSync(indexPath, renderIndex(entries, purposes));
  return { manifestPath, indexPath };
}
